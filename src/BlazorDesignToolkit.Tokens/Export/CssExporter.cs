namespace BlazorDesignToolkit.Tokens.Export;

public enum CssReferenceMode
{
    /// <summary>Emit literal values for every token.</summary>
    Resolve,
    /// <summary>Emit <c>var(--other)</c> for aliases (and aliased composite parts) whose targets are also exported, so runtime overrides cascade.</summary>
    Preserve,
}

public enum CssColorFormat
{
    /// <summary>sRGB colors as hex when they are exact 8-bit values, otherwise the CSS function matching the token's color space (lossless).</summary>
    Auto,
    /// <summary>Always hex (#rrggbb / #rrggbbaa). Out-of-gamut colors are clipped and reported (BDT7003).</summary>
    Hex,
    /// <summary>Always the CSS function matching the token's color space, e.g. <c>oklch()</c> or <c>color(display-p3 …)</c>.</summary>
    Native,
}

public enum CssNameStyle
{
    /// <summary>camelCase and spaces become kebab-case, letters are lower-cased, other characters become '-'.</summary>
    KebabCase,
    /// <summary>Segments are kept as authored; characters that are not valid in CSS identifiers are escaped.</summary>
    Preserve,
}

public sealed record CssExportOptions
{
    public static CssExportOptions Default { get; } = new();

    /// <summary>Prefix for custom-property names, e.g. "ds" produces <c>--ds-color-primary</c>.</summary>
    public string Prefix { get; init; } = "";
    public CssNameStyle NameStyle { get; init; } = CssNameStyle.KebabCase;
    public CssReferenceMode References { get; init; } = CssReferenceMode.Resolve;
    public CssColorFormat ColorFormat { get; init; } = CssColorFormat.Auto;
    public string Selector { get; init; } = ":root";
    /// <summary>Wraps the output in <c>@layer {Layer} { … }</c> when set.</summary>
    public string? Layer { get; init; }
    /// <summary>Also emit sub-properties for typography, border and transition tokens (e.g. <c>--type-body-font-size</c>).</summary>
    public bool ExpandComposites { get; init; } = true;
    public TokenOrdering Ordering { get; init; } = TokenOrdering.Document;
    /// <summary>Emit token descriptions and deprecation notes as CSS comments.</summary>
    public bool IncludeComments { get; init; }
    /// <summary>Emit a "generated file" banner comment.</summary>
    public bool IncludeHeader { get; init; } = true;
    /// <summary>Maximum fractional digits for numbers.</summary>
    public int Precision { get; init; } = 5;
    /// <summary>Restricts which tokens are exported.</summary>
    public Func<ResolvedToken, bool>? Filter { get; init; }
}

/// <summary>A single generated custom-property declaration.</summary>
public sealed record CssDeclaration(string Name, string Value, TokenPath Token, string? Comment = null);

public sealed class CssExportResult(string css, IReadOnlyList<CssDeclaration> declarations, IReadOnlyList<Diagnostic> diagnostics)
{
    public string Css { get; } = css;
    public IReadOnlyList<CssDeclaration> Declarations { get; } = declarations;
    public IReadOnlyList<Diagnostic> Diagnostics { get; } = diagnostics;
}

/// <summary>
/// Generates CSS custom properties from resolved tokens. Output is deterministic, contains no executable content,
/// and escapes all token-derived strings so it is safe to embed inside an HTML &lt;style&gt; element.
/// </summary>
public static class CssExporter
{
    public const string Banner = "/* Generated by BlazorDesignToolkit from design tokens. Do not edit by hand. */";

    public static CssExportResult Export(ResolvedTokenSet set, CssExportOptions? options = null)
    {
        options ??= CssExportOptions.Default;
        var bag = new DiagnosticBag();
        var declarations = GetDeclarations(set, options, bag);
        var sb = new StringBuilder();
        if (options.IncludeHeader) sb.Append(Banner).Append('\n');
        WriteBlock(sb, options.Selector, declarations, options.Layer, options.IncludeComments, indent: "");
        return new CssExportResult(sb.ToString(), declarations, bag.ToSortedList());
    }

    /// <summary>Writes <c>selector { declarations }</c>, optionally inside <c>@layer</c>.</summary>
    public static void WriteBlock(StringBuilder sb, string selector, IReadOnlyList<CssDeclaration> declarations, string? layer, bool includeComments, string indent)
    {
        var inner = indent;
        if (layer is not null)
        {
            sb.Append(indent).Append("@layer ").Append(layer).Append(" {\n");
            inner = indent + "  ";
        }
        sb.Append(inner).Append(selector).Append(" {\n");
        foreach (var d in declarations)
        {
            if (includeComments && d.Comment is not null) sb.Append(inner).Append("  /* ").Append(SanitizeComment(d.Comment)).Append(" */\n");
            sb.Append(inner).Append("  ").Append(d.Name).Append(": ").Append(d.Value).Append(";\n");
        }
        sb.Append(inner).Append("}\n");
        if (layer is not null) sb.Append(indent).Append("}\n");
    }

    /// <summary>Computes declarations for every exportable token (and composite sub-properties), reporting collisions and unsupported values.</summary>
    public static IReadOnlyList<CssDeclaration> GetDeclarations(ResolvedTokenSet set, CssExportOptions options, DiagnosticBag bag)
    {
        ValidatePrefix(options.Prefix, bag);
        IEnumerable<ResolvedToken> tokens = set.Tokens.Where(t => t.IsValid && (options.Filter?.Invoke(t) ?? true));
        if (options.Ordering == TokenOrdering.Alphabetical) tokens = tokens.OrderBy(static t => t.Path);
        var list = tokens.ToList();
        var exported = list.Select(static t => t.Path).ToHashSet();
        var names = new Dictionary<string, TokenPath>(StringComparer.Ordinal);
        var result = new List<CssDeclaration>();
        foreach (var token in list)
        {
            var name = GetVariableName(token.Path, options);
            if (names.TryGetValue(name, out var other))
            {
                bag.Report(DiagnosticCatalog.NameCollision, $"'{token.Path}' and '{other}' both map to the custom property {name}.",
                    token.Path.ToString(), token.Location, actual: name);
                continue;
            }
            names[name] = token.Path;
            var formatter = new Formatter(set, options, exported, bag, token);
            var value = formatter.FormatToken();
            if (value is null) continue;
            result.Add(new CssDeclaration(name, value, token.Path, Comment(token)));
            if (options.ExpandComposites)
            {
                foreach (var (suffix, subValue) in formatter.Expand())
                {
                    var subName = name + "-" + suffix;
                    if (names.TryGetValue(subName, out var clash))
                    {
                        bag.Report(DiagnosticCatalog.NameCollision, $"Expanded property {subName} of '{token.Path}' collides with '{clash}'.",
                            token.Path.ToString(), token.Location, actual: subName);
                        continue;
                    }
                    names[subName] = token.Path;
                    result.Add(new CssDeclaration(subName, subValue, token.Path));
                }
            }
        }
        return result;
    }

    private static string? Comment(ResolvedToken token)
    {
        var parts = new List<string>();
        if (token.Description is not null) parts.Add(token.Description);
        if (token.IsDeprecated) parts.Add("Deprecated" + (token.Deprecation!.Explanation is { } e ? ": " + e : "."));
        return parts.Count == 0 ? null : string.Join(" ", parts);
    }

    public static string GetVariableName(TokenPath path, CssExportOptions? options = null)
    {
        options ??= CssExportOptions.Default;
        var parts = new List<string>();
        if (!string.IsNullOrEmpty(options.Prefix)) parts.Add(options.Prefix);
        foreach (var segment in path.Segments)
        {
            if (segment == TokenPath.RootTokenName) continue;
            var formatted = options.NameStyle == CssNameStyle.KebabCase ? ToKebab(segment) : EscapeIdentifier(segment);
            if (formatted.Length > 0) parts.Add(formatted);
        }
        return "--" + string.Join("-", parts);
    }

    public static bool IsValidPrefix(string prefix) => prefix.All(static c => char.IsAsciiLetterOrDigit(c) || c is '-' or '_');

    private static void ValidatePrefix(string prefix, DiagnosticBag bag)
    {
        if (!IsValidPrefix(prefix))
        {
            bag.Report(DiagnosticCatalog.InvalidIdentifier, $"The CSS prefix '{prefix}' may only contain ASCII letters, digits, '-' and '_'.", actual: prefix);
        }
    }

    public static string ToKebab(string segment)
    {
        var sb = new StringBuilder(segment.Length + 4);
        for (var i = 0; i < segment.Length; i++)
        {
            var c = segment[i];
            if (char.IsAsciiLetterUpper(c))
            {
                var prevLowerOrDigit = i > 0 && (char.IsAsciiLetterLower(segment[i - 1]) || char.IsAsciiDigit(segment[i - 1]));
                var nextLower = i + 1 < segment.Length && char.IsAsciiLetterLower(segment[i + 1]) && i > 0 && char.IsAsciiLetterUpper(segment[i - 1]);
                if (prevLowerOrDigit || nextLower) sb.Append('-');
                sb.Append(char.ToLowerInvariant(c));
            }
            else if (char.IsAsciiLetterOrDigit(c) || c is '-' or '_') sb.Append(c);
            else if (char.IsLetterOrDigit(c)) sb.Append(char.ToLowerInvariant(c));
            else sb.Append('-');
        }
        var collapsed = new StringBuilder(sb.Length);
        foreach (var c in sb.ToString())
        {
            if (c == '-' && collapsed.Length > 0 && collapsed[^1] == '-') continue;
            collapsed.Append(c);
        }
        return collapsed.ToString().Trim('-');
    }

    /// <summary>Escapes a string for use inside a CSS identifier (CSSOM "serialize an identifier", conservative).</summary>
    public static string EscapeIdentifier(string value)
    {
        var sb = new StringBuilder(value.Length);
        foreach (var c in value)
        {
            if (char.IsAsciiLetterOrDigit(c) || c is '-' or '_' || c > 0x7F && !char.IsControl(c) && c is not ('<' or '>')) sb.Append(c);
            else sb.Append('\\').Append(((int)c).ToString("x", CultureInfo.InvariantCulture)).Append(' ');
        }
        return sb.ToString();
    }

    /// <summary>Quotes a string as a CSS string literal, escaping quotes, backslashes, control characters and angle brackets.</summary>
    public static string QuoteString(string value)
    {
        var sb = new StringBuilder(value.Length + 2);
        sb.Append('"');
        foreach (var c in value)
        {
            if (c is '"' or '\\') sb.Append('\\').Append(c);
            else if (char.IsControl(c) || c is (char)60 or (char)62 or (char)0x2028 or (char)0x2029) sb.Append('\\').Append(((int)c).ToString("X", CultureInfo.InvariantCulture)).Append(' ');
            else sb.Append(c);
        }
        sb.Append('"');
        return sb.ToString();
    }

    public static string SanitizeComment(string text)
        => text.Replace("*/", "* /", StringComparison.Ordinal).Replace('<', ' ').Replace('>', ' ').ReplaceLineEndings(" ");

    private static readonly HashSet<string> s_genericFamilies = new(StringComparer.OrdinalIgnoreCase)
    {
        "serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui", "ui-serif", "ui-sans-serif", "ui-monospace",
        "ui-rounded", "math", "emoji", "fangsong",
    };

    public static string FormatNumber(double value, int precision = 5)
    {
        var rounded = Math.Round(value, precision, MidpointRounding.AwayFromZero);
        if (rounded == 0) rounded = 0; // avoid "-0"
        return rounded.ToString("0." + new string('#', Math.Max(precision, 0)), CultureInfo.InvariantCulture);
    }

    /// <summary>Formats a typed value as CSS (no references).</summary>
    public static string? FormatValue(TokenValue value, CssExportOptions? options = null, DiagnosticBag? bag = null, string? tokenPath = null)
    {
        options ??= CssExportOptions.Default;
        var f = new Formatter(null, options, [], bag ?? new DiagnosticBag(), null) { TokenPathOverride = tokenPath };
        return f.Format(value, null);
    }

    private sealed class Formatter(ResolvedTokenSet? set, CssExportOptions options, HashSet<TokenPath> exported, DiagnosticBag bag, ResolvedToken? token)
    {
        public string? TokenPathOverride { get; init; }
        private string TokenPathText => TokenPathOverride ?? token?.Path.ToString() ?? "";

        public string? FormatToken()
        {
            if (options.References == CssReferenceMode.Preserve && token!.AliasOf is { } target && exported.Contains(target))
            {
                return $"var({GetVariableName(target, options)})";
            }
            return Format(token!.Value!, Raw(token.RawValue));
        }

        /// <summary>Raw value used to preserve references in composite parts (only when the raw value is not itself a reference).</summary>
        private SourceNode? Raw(SourceNode raw)
            => options.References == CssReferenceMode.Preserve && !ReferenceSyntax.IsReference(raw) ? raw : null;

        private string? RefPart(SourceNode? raw, string property)
        {
            if (raw is not SourceObject o || set is null || !o.TryGetProperty(property, out var part)) return null;
            return RefNode(part);
        }

        private string? RefNode(SourceNode? part)
        {
            if (part is null || set is null) return null;
            TokenPath? target = null;
            if (part is SourceString s && ReferenceSyntax.TryParseAlias(s.Value, out var alias)) target = alias;
            else if (ReferenceSyntax.TryGetPointer(part, out var pointer) && JsonPointer.TryParse(pointer, out var segs, out _) && segs.Count > 0 && segs[^1] == "$value"
                && segs.Count(static x => x == "$value") == 1) target = new TokenPath(segs.Take(segs.Count - 1));
            return target is { } t && exported.Contains(t) ? $"var({GetVariableName(t, options)})" : null;
        }

        public string? Format(TokenValue value, SourceNode? raw) => value switch
        {
            ColorValue c => FormatColor(c),
            DimensionValue d => Dim(d),
            DurationValue d => FormatNumber(d.Value, options.Precision) + d.Unit,
            NumberValue n => FormatNumber(n.Value, options.Precision),
            FontWeightValue w => FormatNumber(w.Weight, options.Precision),
            FontFamilyValue f => FormatFamily(f),
            CubicBezierValue b => Bezier(b),
            StrokeStyleValue s => FormatStroke(s),
            BorderValue b => FormatBorder(b, raw),
            TransitionValue t => $"{RefPart(raw, "duration") ?? Format(t.Duration, null)} {RefPart(raw, "timingFunction") ?? Bezier(t.TimingFunction)} {RefPart(raw, "delay") ?? Format(t.Delay, null)}",
            ShadowValue s => FormatShadow(s, raw),
            GradientValue g => FormatGradient(g, raw),
            TypographyValue t => FormatTypography(t, raw),
            _ => Unsupported($"type {value.Type}"),
        };

        /// <summary>Sub-properties emitted when <see cref="CssExportOptions.ExpandComposites"/> is enabled.</summary>
        public IEnumerable<(string Suffix, string Value)> Expand()
        {
            var raw = Raw(token!.RawValue);
            switch (token.Value)
            {
                case TypographyValue t:
                    yield return ("font-family", RefPart(raw, "fontFamily") ?? FormatFamily(t.FontFamily));
                    yield return ("font-size", RefPart(raw, "fontSize") ?? Dim(t.FontSize));
                    yield return ("font-weight", RefPart(raw, "fontWeight") ?? FormatNumber(t.FontWeight.Weight, options.Precision));
                    yield return ("letter-spacing", RefPart(raw, "letterSpacing") ?? Dim(t.LetterSpacing));
                    yield return ("line-height", RefPart(raw, "lineHeight") ?? FormatNumber(t.LineHeight, options.Precision));
                    break;
                case BorderValue b when b.Style.Keyword is not null:
                    yield return ("width", RefPart(raw, "width") ?? Dim(b.Width));
                    yield return ("style", RefPart(raw, "style") ?? b.Style.Keyword);
                    yield return ("color", RefPart(raw, "color") ?? FormatColor(b.Color) ?? "currentcolor");
                    break;
                case TransitionValue tr:
                    yield return ("duration", RefPart(raw, "duration") ?? Format(tr.Duration, null)!);
                    yield return ("delay", RefPart(raw, "delay") ?? Format(tr.Delay, null)!);
                    yield return ("timing-function", RefPart(raw, "timingFunction") ?? Bezier(tr.TimingFunction));
                    break;
            }
        }

        private string Dim(DimensionValue d) => FormatNumber(d.Value, options.Precision) + d.Unit;

        private string Bezier(CubicBezierValue b)
            => $"cubic-bezier({FormatNumber(b.X1, options.Precision)}, {FormatNumber(b.Y1, options.Precision)}, {FormatNumber(b.X2, options.Precision)}, {FormatNumber(b.Y2, options.Precision)})";

        private static string FormatFamily(FontFamilyValue f)
            => string.Join(", ", f.Families.Select(static name => s_genericFamilies.Contains(name) ? name.ToLowerInvariant() : QuoteString(name)));

        private string? FormatStroke(StrokeStyleValue s)
            => s.Keyword ?? Unsupported("a strokeStyle object (dashArray/lineCap) has no CSS custom-property equivalent; use a keyword or consume the token through a dedicated exporter");

        private string? FormatBorder(BorderValue b, SourceNode? raw)
        {
            var style = RefPart(raw, "style") ?? b.Style.Keyword;
            if (style is null) return Unsupported("the border uses a strokeStyle object, which CSS border shorthands cannot express");
            var color = RefPart(raw, "color") ?? FormatColor(b.Color);
            return color is null ? null : $"{RefPart(raw, "width") ?? Dim(b.Width)} {style} {color}";
        }

        private string? FormatShadow(ShadowValue s, SourceNode? raw)
        {
            var layers = new List<string>();
            for (var i = 0; i < s.Layers.Count; i++)
            {
                var l = s.Layers[i];
                var layerRaw = raw is SourceArray arr && i < arr.Items.Count ? arr.Items[i] : (s.IsArrayForm ? null : raw);
                var layerRef = RefNode(layerRaw);
                if (layerRef is not null)
                {
                    layers.Add(layerRef);
                    continue;
                }
                var color = RefPart(layerRaw, "color") ?? FormatColor(l.Color);
                if (color is null) return null;
                layers.Add($"{(l.Inset ? "inset " : "")}{RefPart(layerRaw, "offsetX") ?? Dim(l.OffsetX)} {RefPart(layerRaw, "offsetY") ?? Dim(l.OffsetY)} {RefPart(layerRaw, "blur") ?? Dim(l.Blur)} {RefPart(layerRaw, "spread") ?? Dim(l.Spread)} {color}");
            }
            return string.Join(", ", layers);
        }

        private string? FormatGradient(GradientValue g, SourceNode? raw)
        {
            var stops = new List<string>();
            var rawItems = raw is SourceArray arr && arr.Items.Count == g.Stops.Count ? arr.Items : null;
            for (var i = 0; i < g.Stops.Count; i++)
            {
                var stop = g.Stops[i];
                var color = RefPart(rawItems?[i], "color") ?? FormatColor(stop.Color);
                if (color is null) return null;
                stops.Add($"{color} {FormatNumber(stop.Position * 100, options.Precision)}%");
            }
            return string.Join(", ", stops);
        }

        private string FormatTypography(TypographyValue t, SourceNode? raw)
        {
            var weight = RefPart(raw, "fontWeight") ?? FormatNumber(t.FontWeight.Weight, options.Precision);
            var size = RefPart(raw, "fontSize") ?? Dim(t.FontSize);
            var lineHeight = RefPart(raw, "lineHeight") ?? FormatNumber(t.LineHeight, options.Precision);
            var family = RefPart(raw, "fontFamily") ?? FormatFamily(t.FontFamily);
            return $"{weight} {size}/{lineHeight} {family}";
        }

        public string? FormatColor(ColorValue c)
        {
            if (options.ColorFormat == CssColorFormat.Hex)
            {
                var srgb = c.ToSrgb();
                if (!srgb.IsInGamut)
                {
                    bag.Report(DiagnosticCatalog.OutOfGamut, $"'{TokenPathText}' ({c.ColorSpace}) is outside the sRGB gamut and was clipped for hex output.",
                        TokenPathText, token?.Location, actual: c.ColorSpace, remediation: "Use ColorFormat Auto or Native to keep wide-gamut colors.");
                }
                return srgb.ToHex();
            }
            var alpha = c.Alpha < 1 ? " / " + FormatNumber(c.Alpha, options.Precision) : "";
            string Comp(int i, bool percent = false) => c.Components[i] is { } v ? FormatNumber(v, options.Precision) + (percent ? "%" : "") : "none";
            switch (c.ColorSpace)
            {
                case ColorSpaces.Srgb when options.ColorFormat == CssColorFormat.Auto && !c.HasNoneComponent && IsExact8Bit(c):
                    {
                        var rgb = c.ToSrgb();
                        return IsExact(c.Alpha)
                            ? rgb.ToHex(includeAlpha: true)
                            : $"rgb({SrgbColor.To8(rgb.R)} {SrgbColor.To8(rgb.G)} {SrgbColor.To8(rgb.B)}{alpha})";
                    }
                case ColorSpaces.Hsl: return $"hsl({Comp(0)} {Comp(1, true)} {Comp(2, true)}{alpha})";
                case ColorSpaces.Hwb: return $"hwb({Comp(0)} {Comp(1, true)} {Comp(2, true)}{alpha})";
                case ColorSpaces.Lab: return $"lab({Comp(0)} {Comp(1)} {Comp(2)}{alpha})";
                case ColorSpaces.Lch: return $"lch({Comp(0)} {Comp(1)} {Comp(2)}{alpha})";
                case ColorSpaces.Oklab: return $"oklab({Comp(0)} {Comp(1)} {Comp(2)}{alpha})";
                case ColorSpaces.Oklch: return $"oklch({Comp(0)} {Comp(1)} {Comp(2)}{alpha})";
                default: return $"color({c.ColorSpace} {Comp(0)} {Comp(1)} {Comp(2)}{alpha})";
            }
        }

        private static bool IsExact(double v) => v is >= 0 and <= 1 && Math.Abs(v * 255 - Math.Round(v * 255)) < 0.002;

        private static bool IsExact8Bit(ColorValue c)
        {
            return IsExact(c.Components[0]!.Value) && IsExact(c.Components[1]!.Value) && IsExact(c.Components[2]!.Value);
        }

        private string? Unsupported(string reason)
        {
            bag.Report(DiagnosticCatalog.UnsupportedConversion, $"'{TokenPathText}' was not exported to CSS: {reason}.", TokenPathText, token?.Location);
            return null;
        }
    }
}
