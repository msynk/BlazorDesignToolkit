using System.Text.Json;
using BlazorDesignToolkit.Tokens.Diagnostics;
using BlazorDesignToolkit.Tokens.Export;
using BlazorDesignToolkit.Tokens.Tailwind;

namespace BlazorDesignToolkit.Integrations.Tests;

public class TailwindV3Tests
{
    private static JsonElement Theme(string module)
    {
        // The module is "module.exports = <JSON>;" or "export default <JSON>;" — the JSON part is checked structurally.
        var start = module.IndexOf('{', module.IndexOf("*/", StringComparison.Ordinal));
        var json = module[start..module.LastIndexOf(';')];
        return JsonDocument.Parse(json).RootElement.GetProperty("theme");
    }

    [Fact]
    public void Generates_a_preset_that_references_runtime_variables()
    {
        var output = TailwindConfigExporter.Export(Fixture.Light, new TailwindConfigExportOptions { Mappings = Fixture.TailwindMappings, Css = Fixture.Css });
        Assert.Empty(output.Diagnostics);
        Assert.StartsWith("// Generated by BlazorDesignToolkit for Tailwind CSS 3.", output.Content);
        Assert.Contains("module.exports = {", output.Content);
        var extend = Theme(output.Content).GetProperty("extend");
        Assert.Equal("color-mix(in oklab, var(--ds-color-surface-default) calc(<alpha-value> * 100%), transparent)",
            extend.GetProperty("colors").GetProperty("surface-default").GetString());
        Assert.Equal("var(--ds-radius-md)", extend.GetProperty("borderRadius").GetProperty("md").GetString());
        var body = extend.GetProperty("fontSize").GetProperty("body");
        Assert.Equal("var(--ds-typography-body-font-size)", body[0].GetString());
        Assert.Equal("var(--ds-typography-body-line-height)", body[1].GetProperty("lineHeight").GetString());
        Assert.Equal("var(--ds-font-family-sans)", extend.GetProperty("fontFamily").GetProperty("sans").GetString());
        Assert.Equal("var(--ds-easing-standard)", extend.GetProperty("transitionTimingFunction").GetProperty("standard").GetString());
    }

    [Fact]
    public void Options_control_module_syntax_opacity_wrapping_and_extend()
    {
        var output = TailwindConfigExporter.Export(Fixture.Light, new TailwindConfigExportOptions
        {
            Mappings = [new("color.text.*", "color", "color")],
            Css = Fixture.Css,
            Module = TailwindModuleFormat.EsModule,
            OpacityModifiers = false,
            Extend = false,
        });
        Assert.Contains("export default {", output.Content);
        var colors = Theme(output.Content).GetProperty("colors");
        Assert.Equal("var(--ds-color-text-default)", colors.GetProperty("text-default").GetString());
    }

    [Fact]
    public void Screens_are_literal_and_v4_only_namespaces_are_rejected()
    {
        var output = TailwindConfigExporter.Export(Fixture.Light, new TailwindConfigExportOptions
        {
            Mappings = [new("radius.*", "breakpoint"), new("radius.*", "perspective"), new("shadow.*", "inset-shadow")],
            Css = Fixture.Css,
        });
        var screens = Theme(output.Content).GetProperty("extend").GetProperty("screens");
        Assert.Equal("0.5rem", screens.GetProperty("md").GetString());
        Assert.Contains(output.Diagnostics, d => d.RuleId == DiagnosticCatalog.InvalidMapping.Id && d.Actual == "perspective");
        Assert.Contains(output.Diagnostics, d => d.RuleId == DiagnosticCatalog.InvalidMapping.Id && d.Actual == "inset-shadow");
    }

    [Fact]
    public void V4_breakpoints_are_literal_because_media_queries_cannot_use_var()
    {
        var output = TailwindThemeExporter.Export(Fixture.Light, new TailwindExportOptions { Mappings = [new("radius.*", "breakpoint"), new("radius.*", "container")], Css = Fixture.Css });
        Assert.Contains("--breakpoint-md: 0.5rem;", output.Content);
        Assert.Contains("--container-md: 0.5rem;", output.Content);
    }

    [Fact]
    public void Token_text_cannot_break_out_of_the_javascript_string()
    {
        var set = BlazorDesignToolkit.Tokens.Resolution.TokenResolver.Resolve("""
        { "font": { "family": { "evil": { "$type": "fontFamily", "$value": "x\"); require('child_process'); (\"" } } } }
        """);
        var output = TailwindConfigExporter.Export(set, new TailwindConfigExportOptions { Mappings = [new("font.family.*", "font")], Values = IntegrationValueMode.Literal });
        // The whole value stays inside one JSON string literal.
        var family = Theme(output.Content).GetProperty("extend").GetProperty("fontFamily").GetProperty("evil").GetString();
        Assert.Contains("require('child_process')", family);
    }

    [Fact]
    public void Generated_preset_compiles_with_tailwind_v3()
    {
        var tools = Fixture.RequireTools();
        var cli = Path.Combine(tools, "node_modules", "tailwindcss3", "lib", "cli.js");
        if (!File.Exists(cli)) Assert.Skip("Tailwind CSS 3 is not installed. Run 'npm ci' in tests/integration-tools.");
        var work = Fixture.WorkDirectory(tools, "tailwind3");
        var preset = TailwindConfigExporter.Export(Fixture.Light, new TailwindConfigExportOptions { Mappings = Fixture.TailwindMappings, Css = Fixture.Css });
        File.WriteAllText(Path.Combine(work, "tokens.tailwind.cjs"), preset.Content);
        File.WriteAllText(Path.Combine(work, "tailwind.config.cjs"), "module.exports = { content: ['./page.html'], presets: [require('./tokens.tailwind.cjs')] };\n");
        File.WriteAllText(Path.Combine(work, "input.css"), "@tailwind utilities;\n");
        File.WriteAllText(Path.Combine(work, "page.html"),
            "<div class=\"bg-surface-default bg-surface-default/50 text-text-default rounded-md shadow-raised text-body font-sans ease-standard border-border-default\"></div>");
        var (exit, log) = Fixture.RunNode(tools, work, cli, "-c", "tailwind.config.cjs", "-i", "input.css", "-o", "output.css");
        Assert.True(exit == 0, log);
        var css = File.ReadAllText(Path.Combine(work, "output.css"));
        Assert.Contains("background-color: color-mix(in oklab, var(--ds-color-surface-default) calc(var(--tw-bg-opacity, 1) * 100%), transparent)", css);
        Assert.Contains("color-mix(in oklab, var(--ds-color-surface-default) calc(0.5 * 100%), transparent)", css);
        Assert.Contains("border-radius: var(--ds-radius-md)", css);
        Assert.Contains("font-size: var(--ds-typography-body-font-size)", css);
        Assert.Contains("line-height: var(--ds-typography-body-line-height)", css);
        Assert.Contains("font-family: var(--ds-font-family-sans)", css);
        Assert.Contains("transition-timing-function: var(--ds-easing-standard)", css);
        Directory.Delete(work, true);
    }
}
